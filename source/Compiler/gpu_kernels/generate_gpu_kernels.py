"""Regenerates the GPU block-compression kernels (SPIR-V embedded in C++ headers) from AMD's Compressonator CMP_Core HLSL.
    python generate_gpu_kernels.py [path to compressonator]      (default: ../../../dependencies/compressonator)
Needs DXC (the Vulkan SDK's, VULKAN_SDK set). Run it after moving Compressonator to another commit; the headers are checked in, so a
normal build needs no DXC. Bindings (what xtexture_gpu_encoder.h's descriptor layout expects): b0 -> 0, t0/t1 -> 10/11, u0 -> 20."""
import os, struct, subprocess, sys
from pathlib import Path

HERE = Path(__file__).parent
CMP  = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[2] / "dependencies" / "compressonator"
DXC  = Path(os.environ["VULKAN_SDK"]) / ("Bin/dxc.exe" if os.name == "nt" else "bin/dxc")
KERNELS = { "bc1": ["EncodeBlocks"], "bc3": ["EncodeBlocks"], "bc4": ["EncodeBlocks"], "bc5": ["EncodeBlocks"],
            "bc7": ["TryMode456CS", "TryMode137CS", "TryMode02CS", "EncodeBlocks"] }

for k, entries in KERNELS.items():
    out = [f"// Generated by generate_gpu_kernels.py from Compressonator cmp_core/shaders/{k}_encode_kernel.hlsl - do not edit", "#pragma once", "#include <cstdint>", ""]
    for e in entries:
        spv = HERE / f"_{k}_{e}.spv"
        r = subprocess.run([str(DXC), "-HV", "2018", "-spirv", "-T", "cs_6_0", "-E", e, "-fspv-target-env=vulkan1.3", "-fspv-entrypoint-name=main",
                            "-fvk-b-shift", "0", "0", "-fvk-t-shift", "10", "0", "-fvk-u-shift", "20", "0", "-fvk-s-shift", "30", "0",
                            "-Fo", str(spv), str(CMP / "cmp_core" / "shaders" / f"{k}_encode_kernel.hlsl")], capture_output=True, text=True)
        if r.returncode: sys.exit(f"dxc {k} {e} failed:\n{r.stdout}{r.stderr}")
        words = struct.unpack(f"<{spv.stat().st_size // 4}I", spv.read_bytes()); spv.unlink()
        out.append(f"inline constexpr std::uint32_t xtexture_gpu_{k}_{e}_v[] =\n{{")
        out += ["    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 12]) + "," for i in range(0, len(words), 12)]
        out += ["};", ""]
    (HERE / f"xtexture_gpu_{k}.h").write_text("\n".join(out) + "\n")
    print("wrote", f"xtexture_gpu_{k}.h")
